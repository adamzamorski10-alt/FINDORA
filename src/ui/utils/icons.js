export function renderIcon(icon) {
  if (!icon) return '🏦';
  if (ICON_MAP[icon]) return ICON_MAP[icon];
  return icon;
}

export function createSvgIcon(name, className = '', size = 18) {
  const svg = SVG_ICONS[name];
  if (!svg) return null;
  const wrapper = document.createElement('span');
  wrapper.className = className;
  wrapper.innerHTML = svg;
  wrapper.style.display = 'inline-flex';
  wrapper.style.width = `${size}px`;
  wrapper.style.height = `${size}px`;
  wrapper.style.alignItems = 'center';
  wrapper.style.justifyContent = 'center';
  wrapper.style.flexShrink = '0';
  wrapper.querySelector('svg').style.width = '100%';
  wrapper.querySelector('svg').style.height = '100%';
  return wrapper;
}

export function createIconButton(name, label, onClick, variant = 'ghost', size = 'sm') {
  const btn = document.createElement('button');
  btn.type = 'button';
  btn.className = `icon-btn icon-btn--${variant} icon-btn--${size}`;
  btn.setAttribute('aria-label', label || name);
  btn.setAttribute('title', label || name);
  const icon = createSvgIcon(name, '', 18);
  if (icon) btn.appendChild(icon);
  if (typeof onClick === 'function') {
    btn.addEventListener('click', onClick);
  }
  return btn;
}
